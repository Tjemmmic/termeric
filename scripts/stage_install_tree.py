#!/usr/bin/env python3
"""Stage Termeric's install tree: everything an installation puts under its prefix.

The tree is relocatable (Termeric finds its terminfo entry beside its binary),
and it is the one source for every way Termeric ships: the release tarball is
the tree itself, the .deb packages its bin/ and share/, and the PKGBUILD
installs it with the bundled install.sh. MANIFEST lists the files to install
with their modes, one "MODE PATH" line each, for install.sh and the package
checks.

The release workflow runs this on Ubuntu 22.04, so it must stay compatible
with that release's Python 3.10.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import shutil
import sys


ROOT = Path(__file__).resolve().parent.parent
# The window identities in termeric/src/app/mod.rs; desktops match them to the
# desktop entries and icons of the same name.
APP_ID = "org.termeric.Termeric"
QUICK_ACCESS_APP_ID = f"{APP_ID}.QuickAccess"
# Sizes the hicolor theme declares; generated by generate_icons.py.
ICON_SIZES = (16, 24, 32, 48, 64, 128, 256, 512)
MANIFEST_NAME = "MANIFEST"
INSTALLER_NAME = "install.sh"
INSTALLER_SOURCE = "packaging/install.sh"
EXECUTABLE_MODE = 0o755
DATA_MODE = 0o644


class StageError(RuntimeError):
    pass


def tree_sources() -> dict[str, str]:
    """Each installed path below the prefix, apart from the binary, and its source in the repository."""
    sources = {
        f"share/applications/{APP_ID}.desktop": f"assets/{APP_ID}.desktop",
        f"share/applications/{QUICK_ACCESS_APP_ID}.desktop": f"assets/{QUICK_ACCESS_APP_ID}.desktop",
        f"share/metainfo/{APP_ID}.metainfo.xml": f"assets/{APP_ID}.metainfo.xml",
        "share/terminfo/x/xterm-termeric": "assets/terminfo/x/xterm-termeric",
        "share/man/man1/termeric.1": "assets/man/termeric.1",
        "share/bash-completion/completions/termeric": "assets/completions/termeric.bash",
        "share/zsh/site-functions/_termeric": "assets/completions/_termeric",
        "share/fish/vendor_completions.d/termeric.fish": "assets/completions/termeric.fish",
        "share/doc/termeric/README.md": "README.md",
        "share/doc/termeric/CHANGELOG.md": "CHANGELOG.md",
        "share/doc/termeric/FEATURES.md": "FEATURES.md",
        "share/doc/termeric/LICENSE": "LICENSE",
        "share/doc/termeric/THIRD_PARTY_NOTICES.md": "termeric/THIRD_PARTY_NOTICES.md",
        "share/doc/termeric/config.example.toml": "assets/config.example.toml",
    }
    for size in ICON_SIZES:
        icon = f"icons/hicolor/{size}x{size}/apps/{APP_ID}.png"
        sources[f"share/{icon}"] = f"assets/{icon}"
    return sources


def manifest() -> dict[str, int]:
    """Every installed path below the prefix and its mode, in installation order."""
    return {
        "bin/termeric": EXECUTABLE_MODE,
        **{path: DATA_MODE for path in sorted(tree_sources())},
    }


def format_manifest(entries: dict[str, int]) -> str:
    return "".join(f"{mode:o} {path}\n" for path, mode in entries.items())


def parse_manifest(text: str) -> dict[str, int]:
    entries: dict[str, int] = {}
    for line in text.splitlines():
        mode, separator, path = line.partition(" ")
        if not separator or mode not in {"755", "644"} or not path or path in entries:
            raise StageError(f"malformed manifest line: {line!r}")
        entries[path] = int(mode, 8)
    return entries


def copy_file(source: Path, destination: Path, mode: int) -> None:
    if source.is_symlink() or not source.is_file():
        raise StageError(f"missing regular file: {source}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)
    destination.chmod(mode)


def stage(binary: Path, output: Path, repository: Path = ROOT) -> dict[str, int]:
    if not binary.is_file() or binary.read_bytes()[:4] != b"\x7fELF":
        raise StageError(f"not an ELF executable: {binary}")
    # A tree staged earlier could hold files this one no longer ships.
    if output.exists() and (not output.is_dir() or any(output.iterdir())):
        raise StageError(f"output must be a new or empty directory: {output}")
    output.mkdir(parents=True, exist_ok=True)
    copy_file(binary, output / "bin/termeric", EXECUTABLE_MODE)
    for path, source in tree_sources().items():
        copy_file(repository / source, output / path, DATA_MODE)
    copy_file(repository / INSTALLER_SOURCE, output / INSTALLER_NAME, EXECUTABLE_MODE)
    entries = manifest()
    (output / MANIFEST_NAME).write_text(format_manifest(entries), encoding="utf-8")
    (output / MANIFEST_NAME).chmod(DATA_MODE)
    return entries


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--binary", type=Path, required=True, help="the built termeric binary")
    parser.add_argument("--out", type=Path, required=True, help="a new or empty directory")
    arguments = parser.parse_args(argv)
    try:
        entries = stage(arguments.binary, arguments.out)
    except (StageError, OSError) as error:
        print(f"staging the install tree failed: {error}", file=sys.stderr)
        return 1
    print(f"staged {len(entries)} files in {arguments.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
