    struct ShellProbeOptions<'a> {
        home_component: &'a str,
        args: &'a [&'a str],
    }

    fn run_shell_semantics_probe_with_options(
        program: &str,
        shell_name: &'static str,
        rc_path: &str,
        rc_contents: &str,
        expected_support: ShellIntegrationSupport,
        options: ShellProbeOptions<'_>,
    ) {
        use sha2::{Digest, Sha256};
        let program_path = std::fs::canonicalize(program).unwrap();
        let program_digest = format!(
            "{:x}",
            Sha256::digest(std::fs::read(&program_path).unwrap())
        );
        let temp = tempfile::tempdir().unwrap();
        let home = temp.path().join(options.home_component);
        let rc = home.join(rc_path);
        std::fs::create_dir_all(rc.parent().unwrap()).unwrap();
        std::fs::write(&rc, rc_contents).unwrap();
        let version = Command::new(&program_path)
            .arg("--version")
            .env_clear()
            .env("HOME", &home)
            .env("PATH", "/usr/bin:/bin")
            .output()
            .unwrap();
        assert!(version.status.success());
        let version = String::from_utf8(version.stdout).unwrap();
        let version = version.lines().next().unwrap();
        assert!(!version.is_empty());

        let mut config = shell(program, options.args);
        config.env.insert("HOME".into(), home.display().to_string());
        config.env.insert("PWD".into(), home.display().to_string());
        config.env.insert(
            "XDG_CONFIG_HOME".into(),
            home.join(".config").display().to_string(),
        );
        config.env.insert("HISTFILE".into(), "/dev/null".into());
        let isolated_login = shell_name == "bash"
            && bash_launch::classify(&config.args).is_some_and(|options| options.login);
        if isolated_login {
            config.env.insert("PATH".into(), "/usr/bin:/bin".into());
            config.env.insert("LANG".into(), "C.UTF-8".into());
        }
        let launch = prepare_shell_launch_in(&config, &temp.path().join("generated")).unwrap();
        assert_eq!(launch.integration, expected_support);
        let pty = Pty::new_with_environment_policy(
            termeric_core::pty::default_pty_size(100, 30),
            launch.program.as_deref(),
            &launch.args,
            &launch.env,
            &termeric_core::pty::EnvironmentPolicy {
                clear: isolated_login,
                unset: vec![],
            },
        )
        .unwrap();
        let (mut handle, reader) = pty.take_reader();
        let rx = spawn_reader_thread(reader);
        let commands: [&[u8]; 3] = if shell_name == "nushell" {
            [b"print (\n'first:second'\n)\r", b"^false\r", b"exit\r"]
        } else if shell_name == "elvish" {
            [b"echo [\nfirst:second\n]\r", b"false\r", b"exit\r"]
        } else {
            [
                b"printf '%s:%s\\n' first \\\nsecond\r",
                b"false\r",
                b"exit\r",
            ]
        };
        let mut next_command = 0;

        let deadline = Instant::now() + Duration::from_secs(8);
        let mut bytes = Vec::new();
        let mut reader_closed = false;
        let mut capability_replies = 0usize;
        let mut terminal = termeric_core::Terminal::new(100, 30);
        while Instant::now() < deadline {
            match rx.recv_timeout(Duration::from_millis(100)) {
                Ok(PtyEvent::Output(chunk)) => {
                    terminal.process(&chunk);
                    bytes.extend(&chunk);
                    for event in terminal.drain_events() {
                        match event {
                            termeric_core::TerminalEvent::PtyWrite(reply) => {
                                handle.write_all(&reply).unwrap();
                                capability_replies += 1;
                            }
                            termeric_core::TerminalEvent::DynamicColor(
                                termeric_core::DynamicColorOperation::Query {
                                    target: termeric_core::DynamicColorTarget::Background,
                                    ..
                                },
                            ) => {
                                handle
                                    .write_all(b"\x1b]11;rgb:2020/1818/1414\x1b\\")
                                    .unwrap();
                                capability_replies += 1;
                            }
                            _ => {}
                        }
                    }
                    // Editors can consume queued keystrokes while collecting
                    // terminal-query replies. Wait for an input-ready prompt
                    // and the preceding command's completion before each send.
                    // Repaints alone must not advance the input sequence.
                    let tracker = &terminal.shell_integration().prompt_tracker;
                    if next_command < commands.len()
                        && tracker.completed_count() == next_command
                        && tracker.active_region().is_some_and(|region| {
                            region.command_row.is_some() && region.output_row.is_none()
                        })
                    {
                        if next_command == 0 {
                            assert_eq!(
                                terminal.reported_working_directory().map(|cwd| cwd.path()),
                                home.to_str(),
                                "{shell_name}: first input-ready prompt needs the exact cwd"
                            );
                        }
                        handle.write_all(commands[next_command]).unwrap();
                        next_command += 1;
                    }
                }
                Ok(PtyEvent::Closed) => {
                    reader_closed = true;
                    break;
                }
                Ok(PtyEvent::Error(error)) => panic!("{shell_name} PTY failed: {error}"),
                Err(std::sync::mpsc::RecvTimeoutError::Timeout) => {
                    if !handle.is_running() {
                        break;
                    }
                }
                Err(std::sync::mpsc::RecvTimeoutError::Disconnected) => break,
            }
        }
        assert!(
            reader_closed || !handle.is_running(),
            "{shell_name} did not exit after the probe: {}",
            String::from_utf8_lossy(&bytes).escape_debug()
        );

        let stdout = String::from_utf8_lossy(&bytes);
        assert_eq!(
            next_command,
            commands.len(),
            "{shell_name}: not all commands sent"
        );
        assert!(
            stdout.contains(&format!("CUSTOM_RC_{}", shell_name.to_uppercase())),
            "{shell_name} did not load its user rc: {}",
            stdout.escape_debug()
        );
        assert!(
            stdout.contains("first:second"),
            "{shell_name} did not run the multiline command: {}",
            stdout.escape_debug()
        );
        assert!(
            terminal.reported_working_directory().is_some(),
            "{shell_name} emitted no OSC 7 directory report: {}",
            stdout.escape_debug()
        );
        assert_eq!(
            terminal.reported_working_directory().unwrap().path(),
            home.to_str().unwrap(),
            "{shell_name}: cwd report must preserve the actual directory exactly"
        );
        assert_eq!(
            super::cwd_probe_tests::first_cwd_mismatch(&bytes, home.to_str().unwrap()),
            None,
            "{shell_name}: a later correction must not conceal an incorrect cwd report"
        );

        let mut state = crate::harvest::HarvestTerminalState::default();
        let regions = state.observe(&terminal.shell_integration().prompt_tracker, true);
        let exit_codes: Vec<_> = regions
            .iter()
            .filter_map(|region| region.exit_code)
            .collect();
        let expected_exit_codes = if shell_name == "fish" {
            // Fish emits a final region for `exit`; its default status is the
            // preceding command's status. Bash/Zsh exit before the next prompt.
            vec![0, 1, 1]
        } else {
            vec![0, 1]
        };
        assert_eq!(
            exit_codes,
            expected_exit_codes,
            "{shell_name} emitted incomplete command regions {regions:?}: {}",
            stdout.escape_debug()
        );
        assert_eq!(std::fs::read(&rc).unwrap(), rc_contents.as_bytes());
        assert_eq!(std::fs::canonicalize(program).unwrap(), program_path);
        assert_eq!(
            format!(
                "{:x}",
                Sha256::digest(std::fs::read(&program_path).unwrap())
            ),
            program_digest,
            "shell executable changed during acceptance"
        );
        // Emitted only after every semantic assertion passes. Zero replies is
        // explicit: an idle response path is not evidence of a round trip.
        eprintln!(
            "TERMERIC_SHELL_ACCEPTANCE={}",
            serde_json::json!({
                "shell": shell_name,
                "path": program_path,
                "version": version,
                "sha256": program_digest,
                "capability_replies": capability_replies,
            })
        );
    }
