//! Shell launch preparation for OSC 133 semantic prompt marks.

use crate::config::ShellConfig;
use anyhow::{Context, Result};
use std::path::{Path, PathBuf};

const BASH_RC: &str = r#"# Generated by Termeric. User configuration is loaded first.
if [ -r "$HOME/.bashrc" ]; then . "$HOME/.bashrc"; fi
__termeric_user_prompt_command=$PROMPT_COMMAND
__termeric_prompt_command() {
    local __termeric_status=$?
    if [ -n "$__termeric_seen_command" ]; then
        printf '\033]133;D;%s\007' "$__termeric_status"
    fi
    if [ -n "$__termeric_user_prompt_command" ]; then
        eval "$__termeric_user_prompt_command"
    fi
    printf '\033]133;A\007\033]133;B\007'
    __termeric_seen_command=1
}
PROMPT_COMMAND=__termeric_prompt_command
PS0=$'\033]133;C\007'
"#;

const ZSH_RC: &str = r#"# Generated by Termeric. User configuration is loaded first.
if [[ -n "$TERMERIC_ORIGINAL_ZDOTDIR" && -r "$TERMERIC_ORIGINAL_ZDOTDIR/.zshrc" ]]; then
    source "$TERMERIC_ORIGINAL_ZDOTDIR/.zshrc"
elif [[ -r "$HOME/.zshrc" ]]; then
    source "$HOME/.zshrc"
fi
autoload -Uz add-zsh-hook
__termeric_preexec() { printf '\033]133;C\007' }
__termeric_precmd() {
    local __termeric_status=$?
    if [[ -n "$__termeric_seen_command" ]]; then
        printf '\033]133;D;%s\007' "$__termeric_status"
    fi
    printf '\033]133;A\007\033]133;B\007'
    __termeric_seen_command=1
}
add-zsh-hook preexec __termeric_preexec
add-zsh-hook precmd __termeric_precmd
"#;

const FISH_INIT: &str = r#"function __termeric_preexec --on-event fish_preexec; printf '\e]133;C\a'; end; function __termeric_postexec --on-event fish_postexec; printf '\e]133;D;%s\a' $status; end; function __termeric_prompt --on-event fish_prompt; printf '\e]133;A\a\e]133;B\a'; end"#;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShellLaunch {
    pub program: Option<String>,
    pub args: Vec<String>,
    pub env: Vec<(String, String)>,
    pub integration: ShellIntegrationSupport,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ShellIntegrationSupport {
    Enabled(&'static str),
    Unavailable(String),
}

impl ShellIntegrationSupport {
    #[cfg(test)]
    pub fn is_enabled(&self) -> bool {
        matches!(self, Self::Enabled(_))
    }
}

/// Prepare a normal interactive shell launch. Explicit command/script launches
/// are left untouched because injecting an interactive rc file would change
/// their semantics.
pub fn prepare_shell_launch(shell: &ShellConfig) -> ShellLaunch {
    let base = directories::ProjectDirs::from("", "", "termeric")
        .map(|dirs| dirs.config_dir().join("shell-integration"))
        .unwrap_or_else(|| PathBuf::from(".termeric-shell-integration"));
    match prepare_shell_launch_in(shell, &base) {
        Ok(launch) => launch,
        Err(error) => {
            log::warn!("Shell integration could not be prepared: {error:#}");
            ShellLaunch {
                program: shell
                    .program
                    .clone()
                    .or_else(|| std::env::var("SHELL").ok()),
                args: shell.args.clone(),
                env: Vec::new(),
                integration: ShellIntegrationSupport::Unavailable(format!(
                    "Shell integration setup failed: {error:#}"
                )),
            }
        }
    }
}

fn prepare_shell_launch_in(shell: &ShellConfig, base: &Path) -> Result<ShellLaunch> {
    let program = shell
        .program
        .clone()
        .or_else(|| std::env::var("SHELL").ok());
    let mut launch = ShellLaunch {
        program,
        args: shell.args.clone(),
        env: Vec::new(),
        integration: ShellIntegrationSupport::Unavailable(
            "Shell integration is unavailable; configure Bash, Zsh, or Fish".into(),
        ),
    };

    if !is_interactive_launch(&launch.args) {
        launch.integration = ShellIntegrationSupport::Unavailable(
            "Shell integration is disabled for command/script shell arguments".into(),
        );
        return Ok(launch);
    }

    let Some(program) = launch.program.as_deref() else {
        return Ok(launch);
    };
    let shell_name = Path::new(program)
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or(program);

    match shell_name {
        "bash" => {
            let path = write_integration_file(base, "bash", ".bashrc", BASH_RC)?;
            launch
                .args
                .splice(0..0, ["--rcfile".to_string(), path.display().to_string()]);
            launch.integration = ShellIntegrationSupport::Enabled("bash");
        }
        "zsh" => {
            let path = write_integration_file(base, "zsh", ".zshrc", ZSH_RC)?;
            if let Ok(original) = std::env::var("ZDOTDIR") {
                launch
                    .env
                    .push(("TERMERIC_ORIGINAL_ZDOTDIR".into(), original));
            }
            let dir = path.parent().expect("generated zsh rc has a parent");
            launch
                .env
                .push(("ZDOTDIR".into(), dir.display().to_string()));
            launch.integration = ShellIntegrationSupport::Enabled("zsh");
        }
        "fish" => {
            launch
                .args
                .splice(0..0, ["--init-command".into(), FISH_INIT.into()]);
            launch.integration = ShellIntegrationSupport::Enabled("fish");
        }
        _ => {}
    }

    Ok(launch)
}

fn is_interactive_launch(args: &[String]) -> bool {
    !args.iter().any(|arg| {
        matches!(arg.as_str(), "-c" | "--command")
            || (!arg.starts_with('-') && !matches!(arg.as_str(), "login"))
    })
}

fn write_integration_file(
    base: &Path,
    shell: &str,
    filename: &str,
    contents: &str,
) -> Result<PathBuf> {
    let dir = base.join(shell);
    std::fs::create_dir_all(&dir)
        .with_context(|| format!("create shell integration directory {}", dir.display()))?;
    let path = dir.join(filename);
    let current = std::fs::read_to_string(&path).ok();
    if current.as_deref() != Some(contents) {
        std::fs::write(&path, contents)
            .with_context(|| format!("write shell integration file {}", path.display()))?;
    }
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::process::Command;
    use std::time::{Duration, Instant};
    use termeric_core::Pty;
    use termeric_core::pty::{PtyEvent, spawn_reader_thread};

    fn shell(program: &str, args: &[&str]) -> ShellConfig {
        ShellConfig {
            program: Some(program.into()),
            args: args.iter().map(|arg| (*arg).into()).collect(),
        }
    }

    #[test]
    fn supported_shells_receive_semantic_prompt_hooks() {
        let temp = tempfile::tempdir().unwrap();
        let bash = prepare_shell_launch_in(&shell("/bin/bash", &[]), temp.path()).unwrap();
        assert_eq!(bash.args[0], "--rcfile");
        assert!(bash.integration.is_enabled());

        let zsh = prepare_shell_launch_in(&shell("zsh", &["-l"]), temp.path()).unwrap();
        assert!(zsh.env.iter().any(|(key, _)| key == "ZDOTDIR"));
        assert!(zsh.integration.is_enabled());

        let fish = prepare_shell_launch_in(&shell("fish", &[]), temp.path()).unwrap();
        assert_eq!(fish.args[0], "--init-command");
        assert!(fish.integration.is_enabled());
    }

    #[test]
    fn command_launches_and_unknown_shells_are_not_modified() {
        let temp = tempfile::tempdir().unwrap();
        let scripted =
            prepare_shell_launch_in(&shell("bash", &["-c", "echo hi"]), temp.path()).unwrap();
        assert_eq!(scripted.args, vec!["-c", "echo hi"]);
        assert!(!scripted.integration.is_enabled());

        let unknown = prepare_shell_launch_in(&shell("nu", &[]), temp.path()).unwrap();
        assert!(unknown.args.is_empty());
        assert!(!unknown.integration.is_enabled());
    }

    #[test]
    fn bash_integration_emits_real_command_boundaries_when_available() {
        if Command::new("bash").arg("--version").output().is_err() {
            eprintln!("skipping Bash integration smoke test: bash is unavailable");
            return;
        }
        let temp = tempfile::tempdir().unwrap();
        let launch = prepare_shell_launch_in(&shell("bash", &[]), temp.path()).unwrap();
        let pty = Pty::new_with_env(80, 24, launch.program.as_deref(), &launch.args, &launch.env)
            .unwrap();
        let (mut handle, reader) = pty.take_reader();
        let rx = spawn_reader_thread(reader);
        handle
            .write_all(b"printf 'harvest-smoke\\n'\rexit\r")
            .unwrap();
        let deadline = Instant::now() + Duration::from_secs(3);
        let mut bytes = Vec::new();
        while Instant::now() < deadline {
            match rx.recv_timeout(Duration::from_millis(100)) {
                Ok(PtyEvent::Output(chunk)) => bytes.extend(chunk),
                Ok(PtyEvent::Closed | PtyEvent::Error(_)) => break,
                Err(std::sync::mpsc::RecvTimeoutError::Timeout) => continue,
                Err(std::sync::mpsc::RecvTimeoutError::Disconnected) => break,
            }
        }
        let stdout = String::from_utf8_lossy(&bytes);
        assert!(stdout.contains("harvest-smoke"));
        assert!(stdout.contains("\u{1b}]133;A\u{7}"));
        assert!(
            stdout.contains("\u{1b}]133;C\u{7}"),
            "{}",
            stdout.escape_debug()
        );
        assert!(
            stdout.contains("\u{1b}]133;D;0\u{7}"),
            "{}",
            stdout.escape_debug()
        );

        let mut terminal = termeric_core::Terminal::new(80, 24);
        terminal.process(&bytes);
        let mut state = crate::harvest::HarvestTerminalState::default();
        let regions = state.observe(&terminal.shell_integration().prompt_tracker, true);
        assert!(
            !regions.is_empty(),
            "real Bash output produced no command region"
        );
        let mut harvest = crate::harvest::HarvestMode::with_capacity(10);
        for region in regions {
            harvest.record_command(
                crate::harvest::HarvestSource {
                    tab_id: 1,
                    pane_id: None,
                },
                &region,
            );
        }
        assert_eq!(harvest.cellar.len(), 1);
    }
}
