    fn bash_integration_emits_real_command_boundaries_when_available() {
        if Command::new("bash").arg("--version").output().is_err() {
            eprintln!("skipping Bash integration smoke test: bash is unavailable");
            return;
        }
        let temp = tempfile::tempdir().unwrap();
        let launch = prepare_shell_launch_in(&shell("bash", &[]), temp.path()).unwrap();
        let pty = Pty::new_with_env(80, 24, launch.program.as_deref(), &launch.args, &launch.env)
            .unwrap();
        let (mut handle, reader) = pty.take_reader();
        let rx = spawn_reader_thread(reader);
        handle
            .write_all(b"printf 'harvest-smoke\\n'\rexit\r")
            .unwrap();
        let deadline = Instant::now() + Duration::from_secs(3);
        let mut bytes = Vec::new();
        while Instant::now() < deadline {
            match rx.recv_timeout(Duration::from_millis(100)) {
                Ok(PtyEvent::Output(chunk)) => bytes.extend(chunk),
                Ok(PtyEvent::Closed | PtyEvent::Error(_)) => break,
                Err(std::sync::mpsc::RecvTimeoutError::Timeout) => continue,
                Err(std::sync::mpsc::RecvTimeoutError::Disconnected) => break,
            }
        }
        let stdout = String::from_utf8_lossy(&bytes);
        assert!(stdout.contains("harvest-smoke"));
        assert!(stdout.contains("\u{1b}]133;A\u{7}"));
        assert!(stdout.contains("\u{1b}]7;file://"));
        assert!(
            stdout.contains("\u{1b}]133;C\u{7}"),
            "{}",
            stdout.escape_debug()
        );
        assert!(
            stdout.contains("\u{1b}]133;D;0\u{7}"),
            "{}",
            stdout.escape_debug()
        );

        let mut terminal = termeric_core::Terminal::new(80, 24);
        terminal.process(&bytes);
        assert!(
            terminal.reported_working_directory().is_some(),
            "real Bash output produced no OSC 7 directory report: {}",
            stdout.escape_debug()
        );
        let mut state = crate::harvest::HarvestTerminalState::default();
        let regions = state.observe(&terminal.shell_integration().prompt_tracker, true);
        assert!(
            !regions.is_empty(),
            "real Bash output produced no command region"
        );
        let mut harvest = crate::harvest::HarvestMode::with_capacity(10);
        for region in regions {
            harvest.record_command(
                crate::harvest::HarvestSource {
                    tab_id: 1,
                    pane_id: 0,
                },
                &region,
                "printf harvest-smoke",
                false,
                "harvest-smoke",
            );
        }
        assert_eq!(harvest.cellar.len(), 1);
    }

