// Elvish has no pre-REPL command-line hook that preserves an arbitrary rc.elv.
// Make a normal Elvish module discoverable instead; the user opts in once with
// `use termeric-integration`, matching Elvish's documented module model.
const ELVISH_MODULE: &str = r#"{
    use str
    use re

    # Restore only the unchanged value that this launch actually installed.
    # User rc overrides/unsets and imports without transport markers are kept.
    if (and (has-env TERMERIC_ELVISH_INTEGRATION_XDG_DATA_DIRS) (has-env XDG_DATA_DIRS)) {
        var termeric-transport = $E:TERMERIC_ELVISH_INTEGRATION_XDG_DATA_DIRS
        if (and (not-eq $termeric-transport '') (eq $E:XDG_DATA_DIRS $termeric-transport)) {
            if (eq $E:TERMERIC_ELVISH_HAD_XDG_DATA_DIRS 1) {
                if (has-env TERMERIC_ELVISH_ORIGINAL_XDG_DATA_DIRS) {
                    set-env XDG_DATA_DIRS $E:TERMERIC_ELVISH_ORIGINAL_XDG_DATA_DIRS
                }
            } elif (eq $E:TERMERIC_ELVISH_HAD_XDG_DATA_DIRS 0) {
                unset-env XDG_DATA_DIRS
            }
        }
    }
    unset-env TERMERIC_ELVISH_HAD_XDG_DATA_DIRS
    unset-env TERMERIC_ELVISH_ORIGINAL_XDG_DATA_DIRS
    unset-env TERMERIC_ELVISH_INTEGRATION_XDG_DATA_DIRS

    fn termeric-report-pwd {
        var termeric-raw = $pwd
        # count measures bytes in Elvish strings. Reserve seven bytes for
        # file:// within the receiver's 4096-byte URI ceiling.
        if (or (not (str:has-prefix $termeric-raw /)) (> (count $termeric-raw) 4089)) {
            return
        }
        # Ordinary ASCII paths need no per-byte conversion.
        if (re:match '^[a-zA-Z0-9/._~-]+$' $termeric-raw) {
            printf "\e]7;file://%s\a" $termeric-raw
            return
        }
        var termeric-cwd = ''
        for termeric-byte [(str:to-utf8-bytes $termeric-raw)] {
            # Decode only known-safe ASCII. A single UTF-8 continuation or
            # leading byte is not a valid argument to str:from-utf8-bytes.
            var termeric-alnum = (or (<= 48 $termeric-byte 57) (<= 65 $termeric-byte 90) (<= 97 $termeric-byte 122))
            if (or $termeric-alnum (<= 45 $termeric-byte 47) (== $termeric-byte 95) (== $termeric-byte 126)) {
                set termeric-cwd = $termeric-cwd(str:from-utf8-bytes $termeric-byte)
            } else {
                set termeric-cwd = $termeric-cwd(printf '%%%02X' $termeric-byte)
            }
            # Do not emit a partial report when encoding exceeds the cap.
            if (> (count $termeric-cwd) 4089) { return }
        }
        printf "\e]7;file://%s\a" $termeric-cwd
    }
    fn termeric-before-readline {
        termeric-report-pwd
        printf "\e]133;A\a\e]133;B\a"
    }
    fn termeric-after-readline {|_| printf "\e]133;C\a" }
    fn termeric-after-command {|command-info|
        var termeric-status = 0
        if (not-eq $nil $command-info[error]) {
            set termeric-status = 1
            if (has-key $command-info[error] reason) {
                if (has-key $command-info[error][reason] exit-status) {
                    set termeric-status = $command-info[error][reason][exit-status]
                }
            }
        }
        printf "\e]133;D;%s\a" $termeric-status
    }

    set edit:before-readline = [ $@edit:before-readline $termeric-before-readline~ ]
    set edit:after-readline = [ $@edit:after-readline $termeric-after-readline~ ]
    set edit:after-command = [ $@edit:after-command $termeric-after-command~ ]
    set after-chdir = [ $@after-chdir {|_| termeric-report-pwd } ]
}
"#;

const ELVISH_MANUAL_INSTRUCTIONS: &str = "Elvish integration is available; add `use termeric-integration` to your configured rc file (normally ~/.config/elvish/rc.elv) and open a new tab";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShellLaunch {
    pub program: Option<String>,
    pub args: Vec<String>,
    pub env: Vec<(String, String)>,
    pub integration: ShellIntegrationSupport,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ShellIntegrationSupport {
    Enabled(&'static str),
    Unavailable(String),
}

impl ShellIntegrationSupport {
    #[cfg(test)]
    pub fn is_enabled(&self) -> bool {
        matches!(self, Self::Enabled(_))
    }
}

/// Prepare a normal interactive shell launch. Explicit command/script launches
/// are left untouched because injecting an interactive rc file would change
/// their semantics.
pub fn prepare_shell_launch(shell: &ShellConfig) -> ShellLaunch {
    let base = crate::paths::config_dir()
        .map(|dir| dir.join("shell-integration"))
        .unwrap_or_else(|| PathBuf::from(".termeric-shell-integration"));
    match prepare_shell_launch_in(shell, &base) {
        Ok(launch) => launch,
        Err(error) => {
            log::warn!("Shell integration could not be prepared: {error:#}");
            ShellLaunch {
                program: shell
                    .program
                    .clone()
                    .or_else(|| std::env::var("SHELL").ok()),
                args: shell.args.clone(),
                env: shell
                    .env
                    .iter()
                    .map(|(key, value)| (key.clone(), value.clone()))
                    .collect(),
                integration: ShellIntegrationSupport::Unavailable(format!(
                    "Shell integration setup failed: {error:#}"
                )),
            }
        }
    }
}

fn prepare_shell_launch_in(shell: &ShellConfig, base: &Path) -> Result<ShellLaunch> {
    let program = shell
        .program
        .clone()
        .or_else(|| std::env::var("SHELL").ok());
    let mut launch = ShellLaunch {
        program,
        args: shell.args.clone(),
        env: shell
            .env
            .iter()
            .map(|(key, value)| (key.clone(), value.clone()))
            .collect(),
        integration: ShellIntegrationSupport::Unavailable(
            "Shell integration is unavailable; configure Bash, Zsh, Fish, Nushell, or Elvish"
                .into(),
        ),
    };

    let Some(program) = launch.program.as_deref() else {
        return Ok(launch);
    };
    let shell_name = Path::new(program)
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or(program);

    let bash_posix_environment = shell_name == "bash"
        && (effective_env(&launch.env, "POSIXLY_CORRECT").is_some()
            || effective_env(&launch.env, "SHELLOPTS")
                .is_some_and(|options| options.split(':').any(|option| option == "posix")));
    let eligibility_args =
        if shell_name == "bash" && bash_login::is_prepared(&launch.args, &launch.env) {
            &launch.args[1..]
        } else {
            &launch.args[..]
        };
    if bash_posix_environment || !is_interactive_shell_launch(shell_name, eligibility_args) {
        launch.integration = ShellIntegrationSupport::Unavailable(
            if shell_name == "nu" {
                "Nushell integration is disabled for non-REPL, custom-prelude, or unrecognized arguments"
            } else if shell_name == "zsh" {
                "Zsh integration is disabled for command/script, startup-disabled, or unrecognized arguments"
            } else if shell_name == "bash" {
                "Bash integration is disabled for command/script, non-rc startup, or unrecognized arguments"
            } else if shell_name == "fish" {
                "Fish integration is disabled for command/script, startup-disabled, utility, or unrecognized arguments"
            } else if shell_name == "elvish" {
                "Elvish integration is disabled for command/script, startup-disabled, utility, or unrecognized arguments"
            } else {
                "Shell integration is disabled for command/script shell arguments"
            }
            .into(),
        );
        return Ok(launch);
    }

    match shell_name {
        "bash" => {
            let options =
                bash_launch::classify(eligibility_args).expect("Bash eligibility was checked");
            if options.login {
                let content = format!("{}{BASH_HOOKS}", bash_login::STARTUP);
                let path = write_integration_file(base, "bash", ".bash-login", &content)?;
                bash_login::configure(
                    &mut launch.args,
                    &mut launch.env,
                    &path,
                    options.no_profile,
                )?;
            } else {
                let path = write_integration_file(base, "bash", ".bashrc", &bash_rc())?;
                bash_launch::configure(&mut launch.args, &mut launch.env, &path)?;
            }
            launch.integration = ShellIntegrationSupport::Enabled("bash");
        }
        "zsh" => {
            for filename in [".zshenv", ".zprofile"] {
                write_integration_file(base, "zsh", filename, &zsh_startup_stage(filename))?;
            }
            let path = write_integration_file(base, "zsh", ".zshrc", ZSH_RC)?;
            let dir = path.parent().expect("generated zsh rc has a parent");
            configure_zsh_startup(dir, &mut launch.env)?;
            launch.integration = ShellIntegrationSupport::Enabled("zsh");
        }
        "fish" => {
            let index = fish_launch::integration_index(&launch.args)
                .expect("Fish launch eligibility was checked above");
            launch
                .args
                .splice(index..index, ["--init-command".into(), FISH_INIT.into()]);
            launch.integration = ShellIntegrationSupport::Enabled("fish");
        }
        "nu" => {
            launch
                .args
                .splice(0..0, ["--execute".to_string(), NUSHELL_INIT.to_string()]);
            launch.integration = ShellIntegrationSupport::Enabled("nushell");
        }
        "elvish" => {
            write_integration_file(
                base,
                "elvish/lib",
                "termeric-integration.elv",
                ELVISH_MODULE,
            )?;
            elvish_environment::configure(base, &mut launch.env)?;
            launch.integration =
                ShellIntegrationSupport::Unavailable(ELVISH_MANUAL_INSTRUCTIONS.into());
        }
        _ => {}
    }

    Ok(launch)
}

fn is_interactive_shell_launch(shell_name: &str, args: &[String]) -> bool {
    match shell_name {
        "bash" => bash_launch::classify(args).is_some(),
        "zsh" => zsh_launch::is_interactive(args),
        "fish" => fish_launch::integration_index(args).is_some(),
        "nu" => is_interactive_nushell_launch(args),
        "elvish" => elvish_launch::is_interactive(args),
        _ => is_interactive_launch(args),
    }
}

fn is_interactive_nushell_launch(args: &[String]) -> bool {
    // This is an integration eligibility check, not a replacement CLI parser.
    // Only known REPL options may receive our prelude. In particular, utility
    // and server modes (including future flags) must keep their original argv.
    // A user --execute is also left alone: composing arbitrary Nushell source
    // with our prelude cannot be done safely by concatenating arguments.
    let mut args = args.iter();
    while let Some(arg) = args.next() {
        if arg == "--" {
            return args.next().is_none();
        }
        if let Some(long) = arg.strip_prefix("--") {
            let (name, inline) = long
                .split_once('=')
                .map_or((long, None), |(name, value)| (name, Some(value)));
            match name {
                "interactive" | "login" | "no-config-file" | "no-history" | "no-std-lib" => {
                    if inline.is_some() {
                        return false;
                    }
                }
                "include-path" | "config" | "env-config" | "config-home" | "plugin-config"
                | "plugins" | "log-level" | "log-target" | "log-file" | "threads"
                | "table-mode" | "error-style" => {
                    // Scalar values may themselves start with '-' or contain
                    // spaces/equals signs. Consume exactly one argument.
                    let value = inline.or_else(|| args.next().map(String::as_str));
                    if value.is_none_or(str::is_empty) {
                        return false;
                    }
                }
                // Variable-arity and unknown options are deliberately not
                // guessed; Nushell still receives them unchanged.
                _ => return false,
            }
        } else if let Some(short) = arg.strip_prefix('-').filter(|arg| !arg.is_empty()) {
            let mut flags = short.chars();
            while let Some(flag) = flags.next() {
                match flag {
                    'i' | 'l' | 'n' => {}
                    'I' | 'm' => {
                        // Nushell permits -im value and -im=value, but not
                        // concatenated values such as -mrounded.
                        let value = if flags.as_str().is_empty() {
                            args.next().map(String::as_str)
                        } else {
                            flags.as_str().strip_prefix('=')
                        };
                        if value.is_none_or(str::is_empty) {
                            return false;
                        }
                        break;
                    }
                    _ => return false,
                }
            }
        } else {
            return false;
        }
    }
    true
}

fn is_interactive_launch(args: &[String]) -> bool {
    !args.iter().any(|arg| {
        matches!(arg.as_str(), "-c" | "--command")
            || (!arg.starts_with('-') && !matches!(arg.as_str(), "login"))
    })
}

fn zsh_startup_stage(filename: &str) -> String {
    // Source at file scope: putting user startup inside a helper function would
    // turn its ordinary `typeset` declarations into function-local variables.
    // The filename is one of the fixed stage names above, never user input.
    format!(
        r#"# Generated by Termeric. Forward this native startup stage.
typeset -g +x __termeric_zsh_transport_dir="${{TERMERIC_ZSH_INTEGRATION_DIR-}}"
if [[ ${{TERMERIC_ZSH_HAD_ZDOTDIR-}} == 1 ]]; then
    if [[ ${{TERMERIC_ZSH_ZDOTDIR_EXPORTED-1}} == 0 ]]; then
        typeset -g +x ZDOTDIR="${{TERMERIC_ORIGINAL_ZDOTDIR-}}"
    else
        export ZDOTDIR="${{TERMERIC_ORIGINAL_ZDOTDIR-}}"
    fi
elif [[ ${{TERMERIC_ZSH_HAD_ZDOTDIR-}} == 0 ]]; then
    unset ZDOTDIR
fi
unset TERMERIC_ORIGINAL_ZDOTDIR TERMERIC_ZSH_HAD_ZDOTDIR TERMERIC_ZSH_INTEGRATION_DIR TERMERIC_ZSH_ZDOTDIR_EXPORTED
if [[ -r "${{ZDOTDIR-$HOME}}/{filename}" ]]; then
    builtin source "${{ZDOTDIR-$HOME}}/{filename}"
fi
# Respect user suppression and readonly configuration. Native startup continues
# from the user's path when the temporary transport can no longer be used.
if [[ -o rcs && -o interactive && -n $__termeric_zsh_transport_dir && ${{(t)ZDOTDIR-}} != *readonly* ]]; then
    export TERMERIC_ZSH_HAD_ZDOTDIR=${{+ZDOTDIR}}
    export TERMERIC_ORIGINAL_ZDOTDIR="${{ZDOTDIR-}}"
    if [[ ${{(t)ZDOTDIR-}} == *export* ]]; then
        export TERMERIC_ZSH_ZDOTDIR_EXPORTED=1
    else
        export TERMERIC_ZSH_ZDOTDIR_EXPORTED=0
    fi
    export TERMERIC_ZSH_INTEGRATION_DIR="$__termeric_zsh_transport_dir"
    export ZDOTDIR="$__termeric_zsh_transport_dir"
fi
unset __termeric_zsh_transport_dir
"#
    )
}

fn configure_zsh_startup(dir: &Path, env: &mut Vec<(String, String)>) -> Result<()> {
    let dir = dir
        .to_str()
        .context("Zsh shell integration path is not valid UTF-8")?;
    let inherited = effective_env(env, "ZDOTDIR");
    let previous_transport = effective_env(env, "TERMERIC_ZSH_INTEGRATION_DIR");
    // A nested launch can occur before the generated rc consumes its markers
    // (for example, with startup files disabled). Only unwrap a path that is
    // actually our transport. A profile's different ZDOTDIR takes precedence.
    let is_transport = inherited.as_deref() == Some(dir)
        || (inherited.is_some() && inherited == previous_transport);
    let exported = !is_transport
        || effective_env(env, "TERMERIC_ZSH_ZDOTDIR_EXPORTED").as_deref() != Some("0");
    let original = if is_transport {
        match effective_env(env, "TERMERIC_ZSH_HAD_ZDOTDIR").as_deref() {
            Some("0") => None,
            Some("1") => effective_env(env, "TERMERIC_ORIGINAL_ZDOTDIR"),
            // Compatibility with the older single-marker launch wrapper.
            _ => effective_env(env, "TERMERIC_ORIGINAL_ZDOTDIR").filter(|value| !value.is_empty()),
        }
        // Older nested launches could overwrite the original with our own rc
        // directory. That information is lost; never recursively source it.
        .filter(|value| value != dir && Some(value) != previous_transport.as_ref())
    } else {
        inherited
    };
    upsert_env(
        env,
        "TERMERIC_ZSH_HAD_ZDOTDIR",
        if original.is_some() { "1" } else { "0" }.into(),
    );
    upsert_env(
        env,
        "TERMERIC_ORIGINAL_ZDOTDIR",
        original.unwrap_or_default(),
    );
    upsert_env(env, "TERMERIC_ZSH_INTEGRATION_DIR", dir.into());
    upsert_env(
        env,
        "TERMERIC_ZSH_ZDOTDIR_EXPORTED",
        if exported { "1" } else { "0" }.into(),
    );
    upsert_env(env, "ZDOTDIR", dir.into());
    Ok(())
}

fn effective_env(env: &[(String, String)], key: &str) -> Option<String> {
    env.iter()
        .rev()
        .find(|(candidate, _)| candidate == key)
        .map(|(_, value)| value.clone())
        .or_else(|| std::env::var(key).ok())
}

fn upsert_env(env: &mut Vec<(String, String)>, key: &str, value: String) {
    env.retain(|(candidate, _)| candidate != key);
    env.push((key.into(), value));
}

fn write_integration_file(
    base: &Path,
    shell: &str,
    filename: &str,
    contents: &str,
) -> Result<PathBuf> {
    let dir = base.join(shell);
    std::fs::create_dir_all(&dir)
        .with_context(|| format!("create shell integration directory {}", dir.display()))?;
    let path = dir.join(filename);
    let current = std::fs::read_to_string(&path).ok();
    if current.as_deref() != Some(contents) {
        std::fs::write(&path, contents)
            .with_context(|| format!("write shell integration file {}", path.display()))?;
    }
    Ok(path)
}

